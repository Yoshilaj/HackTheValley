def _acceptable(text: str) -> bool:
    t = (text or "").strip()
    if len(t) < 40 or t.startswith("(fake LLM)"):  # FakeLlm placeholder -> use the template
        return False
    low = t.lower()
    return not any(p.lower() in low for p in FORBIDDEN_PHRASES)


def write_summary(db: Session, user: User, data: ReportData, llm: Any) -> tuple[str, str]:
    """(paragraph, 'llm'|'template'). The LLM sees only `data.facts_for_llm()`."""
    if llm is not None:
        from app.services import llm_audit_hook

        try:
            facts = json.dumps(data.facts_for_llm(), ensure_ascii=False, indent=1)
            resp = llm.complete(
                system_prompt(data.language),
                [{"role": "user", "content": "Facts (JSON). Use nothing else:\n" + facts}],
                max_tokens=700, purpose="report_summary",
                audit_hook=llm_audit_hook(db, user.id, f"risk_assessment:{data.assessment_id}"),
            )
            if _acceptable(resp.text):
                return resp.text.strip(), "llm"
            log.info("report summary from LLM rejected; using template", extra={"assessment_id": data.assessment_id})
        except Exception as exc:
            log.warning("report summary LLM call failed", extra={"error": str(exc)})
    return template_summary(data), "template"


