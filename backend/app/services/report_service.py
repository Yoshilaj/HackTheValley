@dataclass
class ReportData:
    """Everything the report shows; JSON-serialisable via `as_dict()`. Built only from DB rows."""

    language: str
    assessment_id: str
    pathway: str
    pathway_name: str
    level: str
    assessed_at: str
    generated_at: str
    patient: dict[str, Any]
    reason_for_referral: list[dict[str, Any]]
    bp: dict[str, Any] | None
    rhythm: list[dict[str, Any]]
    tasks: list[dict[str, Any]]
    patient_context: list[dict[str, Any]]
    medications: list[dict[str, Any]]
    priority: dict[str, Any]
    probabilities: list[dict[str, Any]]
    model_scores: list[dict[str, Any]]
    rule_versions: dict[str, str]
    data_provenance: list[dict[str, Any]]
    data_quality: dict[str, Any]
    missing_inputs: list[str]
    preventive_measures: list[dict[str, Any]]
    references: list[dict[str, Any]]
    disclaimer: str
    summary: str = ""
    summary_source: str = "template"  # llm | template
    extra: dict[str, Any] = field(default_factory=dict)
    #: PD-03B voice-stability evidence (spec §5.5): feature table vs personal baseline + fixed limitation
    voice_stability: dict[str, Any] | None = None

    def as_dict(self) -> dict[str, Any]:
        return json.loads(json.dumps(asdict(self), default=str, ensure_ascii=False))

    def facts_for_llm(self) -> dict[str, Any]:
        """The JSON the narrative may draw on (no summary, no long boilerplate)."""
        d = self.as_dict()
        for k in ("summary", "summary_source", "disclaimer", "extra", "generated_at"):
            d.pop(k, None)
        # identifiers are not needed for the narrative (review fix 11)
        d["patient"] = {k: v for k, v in (d.get("patient") or {}).items() if k not in ("name", "email")}
        if d.get("bp"):
            d["bp"] = {k: v for k, v in d["bp"].items() if k != "readings"} | {"n_readings": len(self.bp["readings"])}
        return d


def _lang(language: str | None, user: User) -> str:
    lang = (language or (user.profile.language if user.profile else None) or "en").lower()
    return "ja" if lang.startswith("ja") else "en"


def _zone(user: User) -> ZoneInfo:
    try:
        return ZoneInfo((user.profile.timezone if user.profile else None) or "America/Toronto")
    except Exception:
        return ZoneInfo("America/Toronto")


def _fmt_dt(dt: datetime | None, zone: ZoneInfo) -> str | None:
    if dt is None:
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(zone).strftime("%Y-%m-%d %H:%M")


def _mean(values: list[float]) -> float | None:
    return round(statistics.fmean(values), 1) if values else None


def _bp_section(db: Session, user_id: str, as_of: datetime, zone: ZoneInfo) -> dict[str, Any] | None:
    start = as_of - timedelta(days=7)
    rows = list(db.scalars(select(BpReading).where(
        BpReading.user_id == user_id, BpReading.measured_at > start, BpReading.measured_at <= as_of,
    ).order_by(BpReading.measured_at)))
    if not rows:
        return None
    valid = [r for r in rows if r.valid]
    by_day: dict[str, list[BpReading]] = {}
    for r in valid:
        by_day.setdefault(r.measured_at.astimezone(zone).date().isoformat(), []).append(r)
    day_means = [(statistics.fmean(x.systolic for x in rs), statistics.fmean(x.diastolic for x in rs))
                 for rs in by_day.values()]

    def sess(name: str) -> dict[str, Any] | None:
        rs = [r for r in valid if r.session == name]
        if not rs:
            return None
        days = {r.measured_at.astimezone(zone).date() for r in rs}
        return {"systolic": _mean([r.systolic for r in rs]), "diastolic": _mean([r.diastolic for r in rs]),
                "n_days": len(days)}

    return {
        "window_start": _fmt_dt(start, zone)[:10], "window_end": _fmt_dt(as_of, zone)[:10],
        "mean_systolic": _mean([s for s, _ in day_means]), "mean_diastolic": _mean([d for _, d in day_means]),
        "n_days": len(by_day), "n_readings": len(rows), "n_invalid": len(rows) - len(valid),
        "n_irregular_pulse_flags": sum(1 for r in rows if r.irregular_pulse_flag),
        "morning": sess("morning"), "evening": sess("evening"),
        "method": "mean of daily means of valid readings (home BP)",
        "readings": [{
            "measured_at": _fmt_dt(r.measured_at, zone), "session": r.session, "systolic": r.systolic,
            "diastolic": r.diastolic, "pulse": r.pulse, "irregular_pulse_flag": r.irregular_pulse_flag,
            "valid": r.valid, "invalid_reason": r.invalid_reason, "source": r.source,
        } for r in rows],
        "sources": sorted({r.source for r in rows}),
    }


def _rhythm_section(db: Session, user_id: str, as_of: datetime, zone: ZoneInfo) -> list[dict[str, Any]]:
    rows = db.scalars(select(DeviceRhythmResult).where(
        DeviceRhythmResult.user_id == user_id, DeviceRhythmResult.recorded_at > as_of - timedelta(days=30),
        DeviceRhythmResult.recorded_at <= as_of,
    ).order_by(DeviceRhythmResult.recorded_at))
    return [{"recorded_at": _fmt_dt(r.recorded_at, zone), "source": r.source,
             "source_name": SOURCE_NAMES.get(r.source, r.source), "label": r.label, "raw_label": r.raw_label}
            for r in rows]


def _task_section(db: Session, user_id: str, pathway: str, as_of: datetime, zone: ZoneInfo) -> list[dict[str, Any]]:
    types = PATHWAY_TASKS.get(pathway) or (
        tuple(t for ts in PATHWAY_TASKS.values() for t in ts) if pathway == "general" else ())
    if not types:
        return []
    out = []
    for task_type in types:
        rows = list(db.scalars(select(AssessmentTask).where(
            AssessmentTask.user_id == user_id, AssessmentTask.task_type == task_type,
            AssessmentTask.valid.is_(True), AssessmentTask.score.is_not(None), AssessmentTask.created_at <= as_of,
        ).order_by(AssessmentTask.created_at)))
        if not rows:
            continue
        latest = rows[-1]
        if latest.created_at < as_of - timedelta(days=30):
            continue
        prior = [r.score for r in rows[:-1] if r.created_at <= as_of - timedelta(days=7)] or [r.score for r in rows[:-1]]
        out.append({
            "task": task_type, "latest_score": round(latest.score, 2), "latest_at": _fmt_dt(latest.created_at, zone),
            "baseline_median": round(statistics.median(prior), 2) if prior else None, "baseline_n": len(prior),
            "n_sessions": len(rows), "protocol_version": latest.protocol_version,
        })
    return out


def _model_scores(db: Session, user_id: str, assessment: RiskAssessment, zone: ZoneInfo) -> list[dict[str, Any]]:
    models = dict(((assessment.model_versions or {}).get("models")) or {})
    if not models:
        return []
    tasks = list(db.scalars(select(AssessmentTask).where(
        AssessmentTask.user_id == user_id, AssessmentTask.model_scores.is_not(None),
        AssessmentTask.created_at <= assessment.created_at,
    ).order_by(AssessmentTask.created_at.desc()).limit(50)))
    out = []
    for name, version in sorted(models.items()):
        latest = next((t for t in tasks if isinstance((t.model_scores or {}).get(name), dict)), None)
        score = (latest.model_scores or {})[name] if latest else {}
        prov = MODEL_PROVENANCE.get(name, {})
        out.append({
            "name": name, "label": prov.get("label", name), "version": version,
            "probability": score.get("probability"), "threshold": score.get("threshold"),
            "scored_at": _fmt_dt(latest.created_at, zone) if latest else None,
            "dataset": prov.get("dataset", "provenance not recorded"),
            "note": prov.get("note") or score.get("calibration_note"),
            "experimental": name in MODEL_PROVENANCE or bool(score.get("experimental")),
        })
    return out


def _probabilities(assessment: RiskAssessment, lang: str) -> list[dict[str, Any]]:
    out = []
    for p in assessment.probabilities or []:
        entry = dict(p)
        name = str(entry.get("name", ""))
        if entry.get("calculator") == "framingham_2008" or entry.get("source_id") == "src_framingham2008":
            entry["label"] = FRAMINGHAM_LABEL[lang]
            entry["is_framingham"] = True
            if entry.get("category"):
                entry["category_label"] = CCS_CATEGORY_LABEL[lang].get(entry["category"], entry["category"])
        elif "suita" in name.lower() or entry.get("source_id") == "src_suita2014":
            entry["label"] = SUITA_LABEL[lang]
            entry["is_suita"] = True
        else:
            entry["label"] = name
        if entry.get("value_display") is None and entry.get("value_pct") is not None:
            entry["value_display"] = str(entry["value_pct"])
        out.append(entry)
    return out


def _data_provenance(db: Session, user_id: str, as_of: datetime, bp: dict | None,
                     rhythm: list[dict], tasks: list[dict]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    if bp:
        out.append({"data": "home blood pressure", "sources": [SOURCE_NAMES.get(s, s) for s in bp["sources"]],
                    "n": bp["n_readings"]})
    if rhythm:
        out.append({"data": "device rhythm results",
                    "sources": sorted({r["source_name"] for r in rhythm}), "n": len(rhythm)})
    if tasks:
        out.append({"data": "in-app assessment tasks", "sources": ["in-app task (self-administered at home)"],
                    "n": sum(t["n_sessions"] for t in tasks)})
    metric_rows = db.execute(select(MetricSample.type, MetricSample.source, func.count(MetricSample.id)).where(
        MetricSample.user_id == user_id, MetricSample.recorded_at > as_of - timedelta(days=30),
        MetricSample.recorded_at <= as_of,
    ).group_by(MetricSample.type, MetricSample.source)).all()
    for mtype, source, n in sorted(metric_rows):
        out.append({"data": f"wearable metric: {mtype}", "sources": [SOURCE_NAMES.get(source, source)], "n": n})
    return out


def _voice_section(assessment: RiskAssessment, lang: str) -> dict[str, Any] | None:
    """PD-03B feature table from the stored evidence (fired rule, else the display-only informational note)."""
    from app.content.loader import get_voice_stability_text

    fired = next((r for r in assessment.fired_rules or [] if r.get("id") == VOICE_RULE_ID), None)
    note = next((i for i in (assessment.data_quality or {}).get("informational") or []
                 if i.get("rule_id") == VOICE_RULE_ID and i.get("evidence")), None)
    src = fired or note
    if src is None:
        return None
    feats = [e["value"] for e in src.get("evidence") or []
             if isinstance(e, dict) and e.get("type") == "voice_trend_feature" and isinstance(e.get("value"), dict)]
    if not feats:
        return None
    text = get_voice_stability_text()
    message = (note or {}).get("message") or text["message"]
    rows = []
    for f in feats:
        rates = f.get("no_change_alert_rates") or {}
        rows.append({
            "feature": f.get("feature"), "label": f.get("label") or f.get("feature"), "task_type": f.get("task_type"),
            "direction": f.get("direction"), "baseline_median": f.get("baseline_median"), "baseline_mad": f.get("baseline_mad"),
            "scale": f.get("scale"), "scale_note": f.get("scale_note"), "k": f.get("k"),
            "k_placeholder": bool(f.get("k_placeholder")), "threshold": f.get("threshold"),
            "recent_values": [r.get("value") for r in f.get("recent") or []],
            "recent_dates": [r.get("date") for r in f.get("recent") or []],
            "n_adverse": f.get("n_adverse"), "n_recent": f.get("n_recent"), "n_baseline": f.get("n_baseline"),
            "status": f.get("status"), "no_change_alert_rate": rates.get("two_of_three"),
            "no_change_alert_k": rates.get("k_table"),
        })
    dq = assessment.data_quality or {}
    return {
        "fired": fired is not None, "rule_id": VOICE_RULE_ID,
        "summary": text["fired_summary"].get(lang) if fired else None,
        "message": message.get(lang) or message.get("en"),
        "limitation": text["report_limitation"][lang],
        "features": rows, "device": dq.get("voice_device"),
        "baseline_sessions": dq.get("voice_baseline_sessions"), "baseline_needed": dq.get("voice_baseline_needed"),
        "sessions_excluded_noise": dq.get("voice_sessions_excluded_noise"),
        "sources": list(VOICE_SOURCES), "refs": [],
    }


def _references(db: Session, assessment: RiskAssessment, probabilities: list[dict],
                extra_ids: list[str] = ()) -> list[dict[str, Any]]:
    ids: list[str] = []
    for rule in assessment.fired_rules or []:
        ids.extend(rule.get("sources") or [])
    ids.extend(extra_ids)
    ids.extend(m.get("source_id") for m in assessment.preventive_measures or [] if m.get("source_id"))
    ids.extend(p.get("source_id") for p in probabilities if p.get("source_id"))
    ordered = list(dict.fromkeys(i for i in ids if i))
    rows = {r.id: r for r in db.scalars(select(ResearchSource).where(ResearchSource.id.in_(ordered)))} if ordered else {}
    out = []
    for n, sid in enumerate(ordered, start=1):
        row = rows.get(sid)
        if row is not None:
            out.append({"n": n, "id": sid, "title": row.title, "authors": row.authors, "year": row.year,
                        "url": row.url, "doi": row.doi, "kind": row.kind, "in_library": True})
        else:
            cat = REFERENCE_CATALOG.get(sid, {})
            out.append({"n": n, "id": sid, "title": cat.get("title") or f"Reference {sid}",
                        "authors": cat.get("authors"), "year": cat.get("year"), "url": None, "doi": cat.get("doi"),
                        "kind": cat.get("kind"), "in_library": False})
    return out


