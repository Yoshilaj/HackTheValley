_GENERAL_OBS_WORDS = ("sleep", "insomnia", "fatigue", "tired", "mood", "stress", "low_energy")
#: never in a clinic report (too sensitive)
_EXCLUDED_OBS_LABELS = frozenset({"suicidal_ideation"})
REPORT_FREE_TEXT_MAX = 200


def observation_relevant(pathway: str, o: Observation) -> bool:
    """Is this observation an input of the report's pathway rules (cardio / cognitive / PD / general)?
    Labels may be free-form ("palpitations at night"), so a known label inside the normalised
    label counts."""
    label = "_".join((o.label or "").lower().replace("-", " ").split())
    if any(x in label for x in _EXCLUDED_OBS_LABELS):
        return False

    def has(keys) -> bool:
        return any(k in label for k in keys)

    if pathway == "cardio":
        return has(_CARDIO_OBS_LABELS) or o.kind == "medication"
    if pathway == "cognitive":
        return o.kind == "functional_change" or has(_COGNITIVE_OBS_LABELS)
    if pathway == "parkinsons":
        return has(_PD_OBS_LABELS)
    return o.kind in ("mood", "lifestyle") or has(_GENERAL_OBS_WORDS)


def _obs_details(o: Observation) -> str | None:
    if not o.free_text:
        return None
    text = " ".join(o.free_text.split())
    return text if len(text) <= REPORT_FREE_TEXT_MAX else text[:REPORT_FREE_TEXT_MAX - 1] + "…"


def build_report_data(db: Session, user: User, assessment: RiskAssessment, language: str | None = None) -> ReportData:
    """Deterministically assemble every fact shown in the report from DB rows (no LLM)."""
    lang = _lang(language, user)
    zone = _zone(user)
    as_of = assessment.created_at or datetime.now(timezone.utc)
    if as_of.tzinfo is None:
        as_of = as_of.replace(tzinfo=timezone.utc)
    profile = user.profile

    reasons = [{"rule_id": r.get("id"), "version": r.get("version"), "level": r.get("level"),
                "text": r.get("summary_text") or "",
                "evidence": [e.get("summary") for e in (r.get("evidence") or []) if isinstance(e, dict) and e.get("summary")],
                "persistence_windows": r.get("persistence_windows")}
               for r in assessment.fired_rules or []]

    bp = _bp_section(db, user.id, as_of, zone) if assessment.pathway in ("cardio", "general") else None
    rhythm = _rhythm_section(db, user.id, as_of, zone) if assessment.pathway in ("cardio", "general") else []
    tasks = _task_section(db, user.id, assessment.pathway, as_of, zone)
    observations = list(db.scalars(select(Observation).where(
        Observation.user_id == user.id, Observation.created_at > as_of - timedelta(days=30),
        Observation.created_at <= as_of + timedelta(minutes=1),
    ).order_by(Observation.created_at)))
    observations = [o for o in observations if observation_relevant(assessment.pathway, o)]
    context = [{"date": _fmt_dt(o.created_at, zone)[:10], "kind": o.kind, "label": o.label, "severity": o.severity,
                "onset": o.onset, "details": _obs_details(o), "source": o.source} for o in observations]
    meds = [m if isinstance(m, dict) else {"name": str(m)} for m in (profile.medications if profile else None) or []]
    probabilities = _probabilities(assessment, lang)

    data = ReportData(
        language=lang,
        assessment_id=assessment.id,
        pathway=assessment.pathway,
        pathway_name=PATHWAY_NAMES.get(assessment.pathway, {}).get(lang, assessment.pathway),
        level=assessment.level,
        assessed_at=_fmt_dt(as_of, zone),
        generated_at=_fmt_dt(datetime.now(timezone.utc), zone),
        patient={
            "name": (profile.display_name if profile else None) or user.email.split("@")[0],
            "age": profile.age if profile else None,
            "sex": profile.sex if profile else None,
            "known_conditions": {k: getattr(profile, k) for k in (
                "known_hypertension", "known_af", "known_chd", "known_pd", "known_dementia",
                "diabetes", "ckd") if profile and getattr(profile, k) is not None},
            "smoking_status": profile.smoking_status if profile else None,
        },
        reason_for_referral=reasons,
        bp=bp,
        rhythm=rhythm,
        tasks=tasks,
        patient_context=context,
        medications=meds,
        priority={"score": assessment.priority_score, "label": PRIORITY_LABEL[lang],
                  "label_en": PRIORITY_LABEL["en"], "kind": "follow_up_priority"},
        probabilities=probabilities,
        model_scores=_model_scores(db, user.id, assessment, zone),
        rule_versions=dict(((assessment.model_versions or {}).get("rules")) or {}),
        data_provenance=_data_provenance(db, user.id, as_of, bp, rhythm, tasks),
        data_quality={k: v for k, v in (assessment.data_quality or {}).items()
                      if k not in ("headline", "informational", "persistence", "trigger")},
        missing_inputs=list(assessment.missing_inputs or []),
        preventive_measures=list(assessment.preventive_measures or []),
        references=[],
        disclaimer=REPORT_DISCLAIMER[lang],
        voice_stability=_voice_section(assessment, lang) if assessment.pathway == "parkinsons" else None,
    )
    data.references = _references(db, assessment, probabilities,
                                  extra_ids=data.voice_stability["sources"] if data.voice_stability else [])
    ref_n = {r["id"]: r["n"] for r in data.references}
    for m in data.preventive_measures:
        if m.get("source_id") in ref_n:
            m["ref"] = ref_n[m["source_id"]]
    if data.voice_stability:
        data.voice_stability["refs"] = [ref_n[sid] for sid in data.voice_stability["sources"] if sid in ref_n]
    return data


